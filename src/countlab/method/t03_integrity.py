"""T03: fail-closed checks of an observed-candidate T1 decision record.

This verifies that a *record* follows declared evidence/decision rules. It does
NOT verify the visual truth of Qwen verdicts, complete scene recall, or absence.
Solver replay below is a reproducibility check, not an independent oracle.
"""
from __future__ import annotations

import hashlib
import json
from typing import Any

from .schema import box_iou, parse_input
from .joint_arbitration import run_joint_arbitration
from .pairwise_allocation import select_pairwise_queries


class DecisionIntegrityError(ValueError):
    """Decision output contradicts its frozen manifest or declared policy."""


def _require(condition: bool, reason: str) -> None:
    if not condition:
        raise DecisionIntegrityError(reason)


def _hash(obj: dict) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def _state(p: Any, selected: set[str]) -> str:
    if p.candidate_id not in selected:
        return "UNKNOWN"
    if p.semantic == p.whole == "YES":
        return "ACCEPTED"
    if p.semantic == p.whole == "NO":
        return "REJECTED"
    return "UNKNOWN"


def validate_joint_t1_integrity(manifest: dict, prediction: dict) -> dict:
    """Validate T1 evidence usage, partition and deterministic replay.

    Strictly tied to `countlab_joint_arbitration_experimental_v1`. Any future
    solver must introduce a new versioned validator, not silently reuse this.
    """
    baseline, rescues, observed_edges = parse_input(manifest)
    _require(isinstance(prediction, dict), "prediction must be an object")
    _require(prediction.get("schema") == "countlab_joint_arbitration_experimental_v1",
             "unsupported decision schema")
    _require(prediction.get("input_sha256") == _hash(manifest), "frozen input SHA256 mismatch")
    _require(prediction.get("method_variant", "joint_t1") == "joint_t1", "wrong method variant")
    policy = prediction.get("joint_policy")
    _require(isinstance(policy, dict), "missing joint policy")
    mandatory = {
        "collision_iou", "identity_min_same_iou", "pairwise_budget", "pairwise_strategy",
        "abstain_on_unresolved", "enable_recovery", "enable_identity",
    }
    _require(set(policy) == mandatory, "unexpected or missing joint policy fields")
    for name in ("enable_recovery", "enable_identity", "abstain_on_unresolved"):
        _require(type(policy[name]) is bool, f"{name} must be boolean")
    for name in ("collision_iou", "identity_min_same_iou"):
        _require(type(policy[name]) in (float, int), f"{name} must be numeric")
    pair_budget = policy["pairwise_budget"]
    _require(pair_budget is None or (type(pair_budget) is int and pair_budget >= 0),
             "invalid pairwise budget")

    active_rescues = rescues if policy["enable_recovery"] else []
    candidates = baseline + active_rescues
    by_id = {p.candidate_id: p for p in candidates}
    selected_raw = prediction.get("selected_candidate_ids")
    _require(isinstance(selected_raw, list) and all(type(cid) is str for cid in selected_raw),
             "invalid selected candidate IDs")
    _require(len(selected_raw) == len(set(selected_raw)) and all(cid in by_id for cid in selected_raw),
             "invalid selected candidate IDs")
    selected = set(selected_raw)
    ranked = sorted(candidates, key=lambda p: (
        -(p.risk_hint if p.risk_hint is not None else
          (1 - p.confidence if p.confidence is not None else .5)), p.candidate_id))
    _require(selected == {p.candidate_id for p in ranked[:len(selected)]},
             "unary selection cannot be produced by frozen risk order")
    states = {cid: _state(p, selected) for cid, p in by_id.items()}
    expect_rejected = sorted(cid for cid, state in states.items() if state == "REJECTED")
    _require(prediction.get("rejected_candidate_ids") == expect_rejected,
             "rejected candidates contradict selected unary evidence")

    expected_plan = select_pairwise_queries(
        baseline, active_rescues, states, budget=pair_budget,
        collision_iou=policy["collision_iou"],
        identity_min_same_iou=policy["identity_min_same_iou"],
        strategy=policy["pairwise_strategy"],
    )
    _require(prediction.get("pairwise_query_plan") == expected_plan,
             "pairwise plan not generated by relation-blind scheduler")
    visible_edges = observed_edges if pair_budget is None else {
        pair: relation for pair, relation in observed_edges.items()
        if pair in {tuple(row["pair"]) for row in expected_plan}
    }
    if not policy["enable_identity"]:
        visible_edges = {}

    groups = prediction.get("predicted_components")
    _require(isinstance(groups, list), "invalid predicted partition")
    group_of: dict[str, set[str]] = {}
    for group in groups:
        _require(isinstance(group, list) and bool(group) and all(type(cid) is str for cid in group),
                 "invalid partition component")
        _require(len(set(group)) == len(group), "duplicated partition component")
        _require(all(cid in by_id and cid not in group_of for cid in group),
                 "unknown or repeated candidate in partition")
        for cid in group:
            _require(states[cid] == "ACCEPTED", "nonaccepted candidate in verified partition")
            group_of[cid] = set(group)
    _require(all(cid in group_of for cid, state in states.items()
                 if state == "ACCEPTED" and by_id[cid].role == "baseline"),
             "verified baseline missing from physical partition")

    unresolved_rows = prediction.get("unresolved_candidates")
    _require(isinstance(unresolved_rows, list), "invalid unresolved list")
    unresolved: dict[str, str] = {}
    for row in unresolved_rows:
        _require(isinstance(row, dict) and row.get("candidate_id") in by_id,
                 "unknown unresolved candidate")
        cid = row["candidate_id"]
        _require(cid not in unresolved and isinstance(row.get("reason"), str),
                 "duplicate or reasonless unresolved candidate")
        unresolved[cid] = row["reason"]
    fallback = prediction.get("fallback_baseline_candidate_ids")
    _require(isinstance(fallback, list) and all(type(cid) is str for cid in fallback),
             "invalid baseline fallback IDs")
    _require(len(set(fallback)) == len(fallback), "duplicated baseline fallback IDs")
    _require(all(cid in {p.candidate_id for p in baseline} for cid in fallback),
             "fallback must contain baseline candidates only")
    for cid in fallback:
        if states[cid] == "REJECTED":
            _require(unresolved.get(cid) == "same_identity_unary_conflict",
                     "rejected baseline counted without explicit identity conflict")
    _require(all(cid in fallback for cid in (p.candidate_id for p in baseline)
                 if states[cid] != "REJECTED"),
             "baseline nonrejected contribution silently removed")

    trace = prediction.get("joint_trace")
    _require(isinstance(trace, list), "invalid decision trace")
    counted_rescue_units = 0
    for row in trace:
        _require(isinstance(row, dict), "invalid trace entry")
        action = row.get("action")
        if action not in {"ADD", "COALESCE"}:
            continue
        members = row.get("rescue_component")
        _require(isinstance(members, list) and bool(members)
                 and all(type(cid) is str for cid in members), "invalid rescue component in trace")
        _require(len(members) == len(set(members))
                 and all(cid in by_id and by_id[cid].role == "rescue" for cid in members),
                 "invalid rescue component in trace")
        _require(all(states[cid] == "ACCEPTED" for cid in members),
                 "rescue trace uses unverified unary evidence")
        overlaps = [p for p in baseline
                    if any(box_iou(p.box, by_id[cid].box) >= policy["collision_iou"]
                           for cid in members)]
        if action == "ADD":
            counted_rescue_units += 1
            _require(all(cid in group_of and group_of[cid] == set(members) for cid in members),
                     "ADD trace does not match exactly one physical component")
            if not overlaps:
                _require(row.get("reason") == "no_baseline_collision",
                         "false ADD reason: collision-free case")
            else:
                _require(row.get("reason") == "observed_different",
                         "false ADD reason: overlapping baseline")
                for base in overlaps:
                    for cid in members:
                        relation = visible_edges.get(tuple(sorted((base.candidate_id, cid))), "UNKNOWN")
                        _require(relation == "DIFFERENT",
                                 "ADD without visible DIFFERENT evidence for every collision")
        else:
            _require(row.get("reason") == "observed_same" and bool(overlaps),
                     "invalid COALESCE reason")
            _require(any(visible_edges.get(tuple(sorted((base.candidate_id, cid)))) == "SAME"
                         for base in overlaps for cid in members),
                     "COALESCE lacks visible SAME evidence")
            accepted_anchors = [base.candidate_id for base in overlaps
                                if states[base.candidate_id] == "ACCEPTED"
                                and any(visible_edges.get(tuple(sorted((base.candidate_id, cid)))) == "SAME"
                                        for cid in members)]
            if accepted_anchors:
                _require(any(all(cid in group_of and anchor in group_of[cid] for cid in members)
                             for anchor in accepted_anchors),
                         "COALESCE trace lost a verified member from physical partition")
            else:
                _require(all(cid not in group_of for cid in members),
                         "COALESCE lacks verified baseline anchor but claims physical partition")

    forced = prediction.get("evaluation_fallback_count")
    _require(type(forced) is int and forced >= 0, "invalid forced count")
    _require(forced == len(fallback) + counted_rescue_units,
             "fallback count differs from count-unit decomposition")
    _require(prediction.get("query_abstained") is (prediction.get("count_status") == "abstained"),
             "abstention status inconsistent")
    _require(prediction.get("count") == (None if prediction["query_abstained"] else forced),
             "reported count contradicts abstention/fallback")

    try:
        expected = run_joint_arbitration(
            manifest, budget=len(selected), collision_iou=policy["collision_iou"],
            identity_min_same_iou=policy["identity_min_same_iou"],
            pairwise_budget=pair_budget, pairwise_strategy=policy["pairwise_strategy"],
            abstain_on_unresolved=policy["abstain_on_unresolved"],
            enable_recovery=policy["enable_recovery"],
            enable_identity=policy["enable_identity"],
        )
    except (ValueError, TypeError, AssertionError) as exc:
        raise DecisionIntegrityError("cannot reproduce declared T1 execution") from exc
    for key in expected:
        if key == "limitations":
            continue
        _require(key in prediction and prediction[key] == expected[key],
                 f"nonreproducible decision field: {key}")
    structural_risks = []
    for pair, relation in sorted(visible_edges.items()):
        a, b = pair
        if a in group_of and b in group_of:
            if relation == "SAME" and group_of[a] != group_of[b]:
                structural_risks.append("visible_SAME_across_counted_components:" + ",".join(pair))
            if relation == "DIFFERENT" and group_of[a] == group_of[b]:
                structural_risks.append("visible_DIFFERENT_within_counted_component:" + ",".join(pair))
    return {
        "schema": "countlab_t03_integrity_v1",
        "status": "RECORD_CONSISTENT_NOT_VISUAL_TRUTH_CERTIFIED",
        "input_sha256": _hash(manifest),
        "prediction_sha256": _hash(prediction),
        "counted_units": forced,
        "fallback_baselines": len(fallback),
        "rescue_additions": counted_rescue_units,
        "structural_risks": structural_risks,
        "warnings": [
            "Replay checks use T1 itself; they are not an independent correctness proof",
            "Unary YES and identity relations are provided evidence, not ground truth",
            "No object proposal recall or scene-wide absence certificate",
        ],
    }
